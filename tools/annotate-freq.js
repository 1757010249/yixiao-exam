// 为表格行追加频次标注
const lines = content.split('\n');
let count = 0;
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  // 匹配表格数据行：| 易错点 | ... |
  const m = line.match(/^\| ([^|]+?) \|/);
  if (!m) continue;
  const cell = m[1].trim();
  // 跳过表头行和分隔行
  if (cell === '易错点' || /^-+$/.test(cell)) continue;
  // 精确匹配频次表
  const exact = freq[cell];
  if (exact !== undefined) {
    // 只在未标注频次的行加
    if (!/⚠.*次/.test(line)) {
      lines[i] = line.replace('| ' + cell + ' |', `| ${cell} ⚠${exact}次 |`);
      count++;
    }
  }
}

content = lines.join('\n');
fs.writeFileSync(file, content, 'utf8');
console.log('已标注', count, '个易错点');
