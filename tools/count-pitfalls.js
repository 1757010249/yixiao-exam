const results = {};
for (const [k, pitfalls] of Object.entries(pitfallGroups)) {
  results[k] = {};
  for (const [pname, re] of Object.entries(pitfalls)) {
    let count = 0;
    const seen = new Set();
    for (const p of parts) {
      const text = p.replace(/\n/g, ' ');
      if (re.test(text)) {
        // 按题目内容去重
        const key = text.slice(0, 40);
        if (!seen.has(key)) { seen.add(key); count++; }
      }
    }
    results[k][pname] = count;
  }
}

for (const [k, pitfalls] of Object.entries(results)) {
  console.log('==', k, '==');
  for (const [pname, count] of Object.entries(pitfalls)) {
    console.log(`  ${count}\t${pname}`);
  }
}

